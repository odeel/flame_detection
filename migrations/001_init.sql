-- Safe to re-run: every statement is idempotent. The script records itself in
-- schema_migrations, so the app's startup migrator will not apply it again.
-- Target: PostgreSQL 14+ (tested on 16).
-- =====================================================================

CREATE TABLE IF NOT EXISTS schema_migrations (
  version    integer PRIMARY KEY,
  name       text        NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);

-- Key/value settings: data and model "generations" drive cache invalidation.
CREATE TABLE IF NOT EXISTS meta (
  key        text PRIMARY KEY,
  value      text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Persistent cache of upstream NASA PSI API responses.
CREATE TABLE IF NOT EXISTS http_cache (
  url        text PRIMARY KEY,
  status     smallint    NOT NULL,
  body       text        NOT NULL,
  fetched_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS http_cache_fetched_at_idx ON http_cache (fetched_at);

-- One row per NASA PSI investigation; the full metadata document lives in `doc`.
CREATE TABLE IF NOT EXISTS psi_investigations (
  accession     text PRIMARY KEY CHECK (accession ~ '^PSI-[0-9]{1,5}$'),
  accession_num integer GENERATED ALWAYS AS (CASE WHEN accession ~ '^PSI-[0-9]{1,5}$' THEN substring(accession FROM 5)::integer END) STORED,
  acronym       text        NOT NULL DEFAULT '',
  title         text        NOT NULL,
  project_type  text        NOT NULL DEFAULT '',
  platform      text        NOT NULL DEFAULT '',
  release_date  text        NOT NULL DEFAULT '',
  total_bytes   bigint      NOT NULL DEFAULT 0 CHECK (total_bytes >= 0),
  file_count    integer     NOT NULL DEFAULT 0 CHECK (file_count >= 0),
  doc           jsonb       NOT NULL,
  fetched_at    timestamptz NOT NULL,
  -- Full-text search over title, objectives, hypothesis and Earth-benefit statements.
  search        tsvector GENERATED ALWAYS AS (
                  setweight(to_tsvector('english', coalesce(title, '') || ' ' || coalesce(acronym, '')), 'A') ||
                  setweight(to_tsvector('english', coalesce(doc->>'objectives', '') || ' ' || coalesce(doc->>'hypothesis', '')), 'B') ||
                  setweight(to_tsvector('english', coalesce(doc->>'earthBenefits', '')), 'C')
                ) STORED
);
CREATE INDEX IF NOT EXISTS psi_investigations_num_idx    ON psi_investigations (accession_num);
CREATE INDEX IF NOT EXISTS psi_investigations_doc_idx    ON psi_investigations USING gin (doc jsonb_path_ops);
CREATE INDEX IF NOT EXISTS psi_investigations_search_idx ON psi_investigations USING gin (search);

-- Experimental (test-matrix) tables published for each investigation.
CREATE TABLE IF NOT EXISTS psi_tables (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  accession text    NOT NULL REFERENCES psi_investigations (accession) ON DELETE CASCADE,
  label     text    NOT NULL,
  file      text    NOT NULL,
  columns   jsonb   NOT NULL CHECK (jsonb_typeof(columns) = 'array'),
  row_count integer NOT NULL CHECK (row_count >= 0),
  UNIQUE (accession, file)
);
CREATE INDEX IF NOT EXISTS psi_tables_accession_idx ON psi_tables (accession);

-- One row per ISS test point; `cells` is the row as a JSON array aligned with psi_tables.columns.
CREATE TABLE IF NOT EXISTS psi_test_points (
  table_id  integer NOT NULL REFERENCES psi_tables (id) ON DELETE CASCADE,
  row_index integer NOT NULL CHECK (row_index >= 0),
  cells     jsonb   NOT NULL CHECK (jsonb_typeof(cells) = 'array'),
  PRIMARY KEY (table_id, row_index)
);

-- Versioned machine-learning model artifacts.
CREATE TABLE IF NOT EXISTS models (
  id             text             NOT NULL,
  version        integer          NOT NULL CHECK (version > 0),
  title          text             NOT NULL,
  task           text             NOT NULL CHECK (task IN ('classification', 'regression')),
  algorithm      text             NOT NULL,
  primary_metric text             NOT NULL,
  score          double precision,
  n              integer          NOT NULL CHECK (n > 0),
  data_hash      text             NOT NULL,
  trained_at     timestamptz      NOT NULL,
  artifact       jsonb            NOT NULL,
  active         boolean          NOT NULL DEFAULT false,
  PRIMARY KEY (id, version)
);
-- Exactly one active version per model, enforced by the database.
CREATE UNIQUE INDEX IF NOT EXISTS models_one_active_idx ON models (id) WHERE active;

-- Audit log of predictions served by the API.
CREATE TABLE IF NOT EXISTS predictions (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  model_id   text             NOT NULL,
  version    integer          NOT NULL,
  input      jsonb            NOT NULL,
  output     double precision NOT NULL,
  created_at timestamptz      NOT NULL DEFAULT now(),
  FOREIGN KEY (model_id, version) REFERENCES models (id, version) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS predictions_model_time_idx ON predictions (model_id, created_at DESC);

-- Ingest / training job history.
CREATE TABLE IF NOT EXISTS jobs (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kind        text        NOT NULL CHECK (kind IN ('ingest', 'train')),
  status      text        NOT NULL CHECK (status IN ('running', 'succeeded', 'failed')),
  started_at  timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  detail      jsonb
);
CREATE INDEX IF NOT EXISTS jobs_started_idx ON jobs (id DESC);
-- At most one running job of each kind, even across several app servers.
CREATE UNIQUE INDEX IF NOT EXISTS jobs_one_running_idx ON jobs (kind) WHERE status = 'running';

-- API keys for multi-user access. Only the SHA-256 hash of each key is stored.
CREATE TABLE IF NOT EXISTS api_keys (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
  role         text        NOT NULL CHECK (role IN ('reader', 'admin')),
  key_prefix   text        NOT NULL,             -- first characters, shown in listings to identify a key
  key_hash     text        NOT NULL UNIQUE,      -- sha256(key) as hex
  created_at   timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz,
  revoked_at   timestamptz
);
CREATE INDEX IF NOT EXISTS api_keys_active_idx ON api_keys (key_hash) WHERE revoked_at IS NULL;

-- Record this migration.
INSERT INTO schema_migrations (version, name) VALUES (1, '001_init.sql') ON CONFLICT (version) DO NOTHING;
